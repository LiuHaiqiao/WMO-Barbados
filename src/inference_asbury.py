"""
inference_asbury.py — Auto-regressive flood-depth inference for the Asbury Park domain.

Adapted from inference.py (Barbados training domain). Differences:
  - Static features live in Asbury_Park/DEM/ on a 936×1080 EPSG:26918 grid
    (30 m cells, matching the training domain's pixel dimensions and
    resolution). dem.tif is already in metres; --dem_unit ft converts
    legacy feet DEMs on load.
  - Rainfall forcing comes from MRMS hourly QPE GeoTIFFs (lat/lon, ~1 km cells)
    named YYYYMMDD-HHMMSS.tif in US Eastern local time; each is reprojected
    onto the model grid at load time.
  - No ground truth exists for this domain, so there is no --eval; the GIF
    shows Rainfall | Prediction panels (over satellite imagery if available).
  - The initial condition is generated by rolling the model through a short
    spin-up under small uniform rainfall (--spinup_steps/--spinup_rain;
    --spinup_steps 0 gives a zero-depth cold start), and after every rollout
    step depths below 1 mm are zeroed to stop accumulation error.
  - All units are metric: the DEM (dem.tif, from the 10 m bathy-gap-filled
    grid) and every output depth (GeoTIFF bands, max-depth raster, colorbars)
    are in METRES; the model itself runs in its native normalised-mm units.

Usage
-----
python inference_asbury.py \
    --ckpt_path  logs/tfno_.../checkpoints/best.ckpt \
    --model_type fno \
    --gif

# restrict to a sub-window of the downloaded rain series (Eastern local time)
python inference_asbury.py \
    --ckpt_path  logs/tfno_.../checkpoints/best.ckpt \
    --model_type fno \
    --start_time 2026-07-06T00:00 --end_time 2026-07-07T00:00
"""

