FT_TO_M = 0.3048

_DEFAULT_STATIC_DIR = Path('/home/hl1138/surrogate/Asbury_Park/DEM')
_DEFAULT_RAIN_DIR   = Path('/home/hl1138/surrogate/Asbury_Park/rainfall')
_DEM_NAME           = 'NJDEM_150ft_AsburyPark_512.tif'

# Depths below this (m) are filtered out of all depth visualisations
# (0.1 m = common "actionable depth" convention in urban flood mapping)
_WET_THRESHOLD = 0.1

# Depths below this (m, = 1 mm) are zeroed after every rollout step so numerical
# residue can't accumulate over long auto-regressive runs
_MIN_DEPTH_M = 0.001

# Colourful hazard ramp for depth: bright blue → cyan → green → yellow → red
# (turbo with its muddy dark-navy start trimmed so shallow water stays vivid)
_FLOOD_CMAP = mcolors.LinearSegmentedColormap.from_list(
    'flood', plt.get_cmap('turbo')(np.linspace(0.12, 1.0, 256)))

# MRMS clips carry a GRIB pseudo-CRS (sometimes dropped on write); their
# coordinates are plain lon/lat, so treat them as WGS84.
_RAIN_FALLBACK_CRS = 'EPSG:4326'


