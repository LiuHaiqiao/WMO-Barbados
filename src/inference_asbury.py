def save_geotiff(preds, times, grid, out_path: Path) -> None:
    """Save predicted depth sequence as a multi-band GeoTIFF (metres, float32)."""
    profile = grid['profile'].copy()
    profile.update(count=len(preds), dtype='float32', nodata=-9999.0)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with rasterio.open(out_path, 'w', **profile) as dst:
        for i, (pred, t) in enumerate(zip(preds, times)):
            band = pred.squeeze(0).numpy().clip(0, 30.0).astype(np.float32)
            dst.write(band, i + 1)
            label = (t + timedelta(hours=1)).strftime('%Y-%m-%d %H:%M')
            dst.update_tags(i + 1, description=f'pred depth (m) at {label} local')

    print(f'Saved {len(preds)}-band GeoTIFF → {out_path}')


def save_max_depth(preds, land_mask, grid, out_stem: Path,
                   satellite: np.ndarray | None = None, zoom=None) -> None:
    """Per-pixel temporal max depth: GeoTIFF + PNG (over satellite if given)."""
    max_depth = torch.stack(preds, dim=0).max(dim=0).values   # (1, H, W)
    arr = max_depth.squeeze(0).numpy().astype(np.float32)
    land = land_mask.squeeze(0).numpy() > 0

    profile = grid['profile'].copy()
    profile.update(count=1, dtype='float32', nodata=-9999.0)
    tif_path = out_stem.with_name(out_stem.name + '_max_depth.tif')
    with rasterio.open(tif_path, 'w', **profile) as dst:
        dst.write(np.where(land, arr, -9999.0), 1)
        dst.update_tags(1, description='temporal max water depth (m)')
    print(f'Saved max-depth GeoTIFF → {tif_path}')

    vmax = max(float(arr[land].max()), 1e-3)
    fig, ax = plt.subplots(figsize=(7, 7))
    fig.patch.set_facecolor('#1a1a2e')
    im = _overlay_depth(ax, arr, satellite, land, vmax, zoom=zoom)
    ax.set_title('Pred max depth', color='white', fontsize=13, pad=6)
    ax.axis('off')
    cb = plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    cb.set_label('m', color='white', fontsize=10)
    cb.ax.yaxis.set_tick_params(color='white', labelcolor='white')
    cb.outline.set_edgecolor('white')
    png_path = out_stem.with_name(out_stem.name + '_max_depth.png')
    fig.savefig(str(png_path), dpi=150, bbox_inches='tight',
                facecolor=fig.get_facecolor())
    plt.close(fig)
    print(f'Saved max-depth plot → {png_path}')


def save_gif(
    preds, times, rain_seq, land_mask, gif_path: Path,
    fps: int = 2, max_depth: float | None = None, max_rain: float | None = None,
    satellite: np.ndarray | None = None, zoom=None,
) -> None:
    """Two-panel animated GIF: Rainfall | Prediction over satellite imagery."""
    land = land_mask.squeeze(0).numpy() > 0

    if max_depth is None:
        max_depth = max(float(p.squeeze(0).numpy()[land].max()) for p in preds)
        max_depth = max(max_depth, 1e-3)
    if max_rain is None:
        max_rain = max(float(r.max().item()) * NORM_RAIN for r in rain_seq)
        max_rain = max(max_rain, 1.0)

    gif_path.parent.mkdir(parents=True, exist_ok=True)
    frames = []
    for pred, rain, t in tqdm(zip(preds, rain_seq, times),
                              total=len(preds), desc='Rendering GIF', unit='frame'):
        p_np = pred.squeeze(0).numpy()
        r_np = rain.squeeze(0).numpy() * NORM_RAIN
        if zoom is not None:
            r0, r1, c0, c1 = zoom
            r_np = r_np[r0:r1, c0:c1]

        fig, axes = plt.subplots(1, 2, figsize=(11, 5))
        fig.patch.set_facecolor('#1a1a2e')

        im = axes[0].imshow(r_np, cmap='YlGnBu',
                            norm=mcolors.PowerNorm(gamma=_DEPTH_GAMMA, vmin=0,
                                                   vmax=max(max_rain, 1e-6)),
                            origin='upper', aspect='equal', interpolation='nearest')
        axes[0].set_title('Rainfall', color='white', fontsize=12, pad=6)
        ims = [(im, 'mm/hr')]

        im = _overlay_depth(axes[1], p_np, satellite, land, max_depth, zoom=zoom)
        axes[1].set_title('Prediction', color='white', fontsize=12, pad=6)
        ims.append((im, 'm'))

        for ax, (im, unit) in zip(axes, ims):
            ax.axis('off')
            cb = plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
            cb.set_label(unit, color='white', fontsize=9)
            cb.ax.yaxis.set_tick_params(color='white', labelcolor='white')
            cb.outline.set_edgecolor('white')
        fig.suptitle(f"{t.strftime('%Y-%m-%d %H:%M')} local",
                     color='white', fontsize=13, y=1.01)
        fig.tight_layout()

        fig.canvas.draw()
        buf = np.frombuffer(fig.canvas.buffer_rgba(), dtype=np.uint8)
        w, h = fig.canvas.get_width_height()
        frames.append(buf.reshape(h, w, 4)[..., :3])
        plt.close(fig)

    imageio.mimsave(str(gif_path), frames, fps=fps, loop=0)
    print(f'Saved {len(frames)}-frame GIF → {gif_path}')


