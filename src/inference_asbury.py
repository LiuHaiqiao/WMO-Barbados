def load_static(static_dir: Path, dem_unit: str = 'm'):
    """Return (static (4,H,W), land_mask (1,H,W), grid profile dict)."""
    dem_path = static_dir / 'dem.tif'
    if not dem_path.exists():
        dem_path = static_dir / _DEM_NAME

    with rasterio.open(dem_path) as src:
        grid = {'crs': src.crs, 'transform': src.transform,
                'width': src.width, 'height': src.height,
                'profile': src.profile.copy()}

    dem = _read(dem_path)
    if dem_unit == 'ft':
        dem *= FT_TO_M                                   # training DEM is metres
    dem      = dem / NORM_DEM
    manning  = _read(static_dir / 'manning_coef.tif')  / NORM_MAN
    pervious = _read(static_dir / 'pervious_cover.tif')
    slope    = _read(static_dir / 'slope.tif')         / NORM_SLOPE
    static   = torch.from_numpy(np.stack([dem, manning, pervious, slope], axis=0))

    mask = torch.from_numpy(_read(static_dir / 'land_mask.tif')[None].astype(np.float32))
    return static, mask, grid


def load_satellite(sat_path: Path, grid: dict) -> np.ndarray | None:
    """Return an (H, W, 3) float RGB array in [0,1] on the model grid, or None."""
    if sat_path is None or not sat_path.exists():
        return None
    with rasterio.open(sat_path) as src:
        H, W = grid['height'], grid['width']
        if (src.width, src.height) == (W, H) and src.transform == grid['transform']:
            rgb = src.read()
        else:
            rgb = np.zeros((3, H, W), dtype=np.uint8)
            for i in range(3):
                reproject(src.read(i + 1), rgb[i],
                          src_transform=src.transform, src_crs=src.crs,
                          dst_transform=grid['transform'], dst_crs=grid['crs'],
                          resampling=Resampling.average)
    return np.moveaxis(rgb, 0, -1).astype(np.float32) / 255.0


# gamma < 1 spreads colour resolution over shallow/mid depths instead of letting
# a few extreme pixels compress everything into the pale end (range unchanged)
_DEPTH_GAMMA = 0.4


def _overlay_depth(ax, depth_np, satellite, land, vmax, zoom=None):
    """Draw depth on ax — over the satellite RGB if given, else standalone."""
    masked = depth_np.copy()
    norm = mcolors.PowerNorm(gamma=_DEPTH_GAMMA, vmin=0, vmax=max(vmax, 1e-6))
    if zoom is not None:
        r0, r1, c0, c1 = zoom
        masked = masked[r0:r1, c0:c1]
        land = land[r0:r1, c0:c1]
        satellite = satellite[r0:r1, c0:c1] if satellite is not None else None
    if satellite is not None:
        ax.imshow(satellite, origin='upper', aspect='equal', interpolation='nearest')
        wet = (masked >= _WET_THRESHOLD) & land
        masked[~wet] = np.nan                        # dry/ocean → see-through
        # opacity follows the same nonlinear ramp as the colours
        alpha = np.zeros_like(masked)
        alpha[wet] = 0.35 + 0.5 * np.clip(masked[wet] / max(vmax, 1e-6), 0, 1) ** _DEPTH_GAMMA
        return ax.imshow(masked, cmap=_FLOOD_CMAP, norm=norm, alpha=alpha,
                         origin='upper', aspect='equal', interpolation='nearest')
    masked[(masked < _WET_THRESHOLD) | ~land] = np.nan
    return ax.imshow(masked, cmap=_FLOOD_CMAP, norm=norm,
                     origin='upper', aspect='equal', interpolation='nearest')


def load_rain_sequence(
    rain_dir:   Path,
    grid:       dict,
    start_time: datetime | None = None,
    end_time:   datetime | None = None,
):
    """
    Load MRMS hourly rain tifs, reproject each onto the model grid.

    Returns (times, rain_seq): parallel lists of datetimes and normalised
    (1, H, W) tensors.
    """
    entries = []
    for f in sorted(rain_dir.glob('*.tif')):
        try:
            t = datetime.strptime(f.stem, '%Y%m%d-%H%M%S')
        except ValueError:
            continue
        if start_time is not None and t < start_time:
            continue
        if end_time is not None and t > end_time:
            continue
        entries.append((t, f))

    if len(entries) < 2:
        raise FileNotFoundError(
            f'Need at least 2 hourly rain files in {rain_dir} within the '
            f'requested window, found {len(entries)}')

    gaps = [b[0] for a, b in zip(entries, entries[1:])
            if b[0] - a[0] != timedelta(hours=1)]
    if gaps:
        print(f'[load_rain_sequence] WARNING: {len(gaps)} gap(s) in the hourly '
              f'series, first at {gaps[0]}')

    H, W = grid['height'], grid['width']
    times, seq = [], []
    for t, f in tqdm(entries, desc='Reprojecting rain', unit='file'):
        with rasterio.open(f) as src:
            rain = src.read(1).astype(np.float32)
            rain = np.maximum(rain, 0.0)                 # MRMS missing flags < 0
            dst  = np.zeros((H, W), dtype=np.float32)
            reproject(
                rain, dst,
                src_transform=src.transform,
                src_crs=src.crs or _RAIN_FALLBACK_CRS,
                dst_transform=grid['transform'], dst_crs=grid['crs'],
                resampling=Resampling.bilinear,
            )
        times.append(t)
        seq.append(torch.from_numpy(dst[None] / NORM_RAIN))
    return times, seq


# --------------------------------------------------------------------------- #
# Full auto-regressive rollout (no GT exists for this domain)
# --------------------------------------------------------------------------- #

def _zero_small_depth(depth_norm: torch.Tensor) -> torch.Tensor:
    """Zero depths below _MIN_DEPTH_M (input is normalised depth, mm/NORM_DEPTH)."""
    thr = _MIN_DEPTH_M * 1000.0 / NORM_DEPTH
    return torch.where(depth_norm < thr, torch.zeros_like(depth_norm), depth_norm)


def spin_up(
    model:      torch.nn.Module,
    static:     torch.Tensor,       # (4, H, W)
    steps:      int,
    rain_mmhr:  float,
    patch_size: int,
    stride:     int,
    device:     torch.device,
) -> tuple[torch.Tensor, torch.Tensor]:
    """
    Generate an initial depth state by rolling the model under a small uniform
    rainfall for `steps` hours, starting from zero depth.

    Returns (depth (1,H,W) normalised, last rain field (1,H,W) normalised) to
    seed the real rollout.
    """
    hann      = _hann2d(patch_size)
    H, W      = static.shape[1:]
    rain      = torch.full((1, H, W), rain_mmhr / NORM_RAIN)
    depth_t   = torch.zeros_like(rain)
    rain_prev = torch.zeros_like(rain)

    for _ in tqdm(range(steps), desc=f'Spin-up ({rain_mmhr} mm/hr)', unit='step'):
        x_full  = torch.cat([static, rain_prev, rain, depth_t], dim=0)
        depth_t = _zero_small_depth(patched_forward(
            model, x_full, patch_size, stride, device, hann))
        rain_prev = rain

    d_m = depth_t * NORM_DEPTH / 1000.0
    print(f'[spin_up] initial condition after {steps} h: '
          f'max {d_m.max().item():.3f} m, mean {d_m.mean().item():.4f} m, '
          f'wet(>{_MIN_DEPTH_M} m) {100 * (d_m > _MIN_DEPTH_M).float().mean().item():.1f}%')
    return depth_t, rain


def run_inference(
    model:      torch.nn.Module,
    static:     torch.Tensor,       # (4, H, W)
    rain_seq:   list[torch.Tensor],
    patch_size: int,
    stride:     int,
    device:     torch.device,
    init_depth: torch.Tensor | None = None,   # (1,H,W) normalised
    init_rain:  torch.Tensor | None = None,   # (1,H,W) normalised
) -> list[torch.Tensor]:
    """
    Roll out depth auto-regressively from init_depth (zero if None).

    After every step, depths below _MIN_DEPTH_M are zeroed so tiny numerical
    residue cannot accumulate over long rollouts.

    preds[i] is the depth (metres, (1,H,W)) after the rain hour rain_seq[i],
    i.e. at time times[i] + 1 h.
    """
    hann      = _hann2d(patch_size)
    depth_t   = init_depth if init_depth is not None else torch.zeros_like(rain_seq[0])
    rain_prev = init_rain  if init_rain  is not None else torch.zeros_like(rain_seq[0])

    predictions = []
    for t in tqdm(range(len(rain_seq)), desc='Rolling out', unit='step'):
        rain_t = rain_seq[t]
        x_full = torch.cat([static, rain_prev, rain_t, depth_t], dim=0)  # (7,H,W)
        depth_next = _zero_small_depth(patched_forward(
            model, x_full, patch_size, stride, device, hann
        ))                                                               # (1,H,W) norm
        predictions.append(depth_next * NORM_DEPTH / 1000.0)            # → m
        rain_prev = rain_t
        depth_t   = depth_next

    return predictions


