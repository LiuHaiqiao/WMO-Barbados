def main():
    args = parse_args()
    _set_deterministic(args.seed)
    device = torch.device(args.device)

    start_time = datetime.fromisoformat(args.start_time) if args.start_time else None
    end_time   = datetime.fromisoformat(args.end_time)   if args.end_time   else None

    static, land_mask, grid = load_static(Path(args.static_dir), args.dem_unit)
    times, rain_seq = load_rain_sequence(
        Path(args.rain_dir), grid, start_time, end_time)

    satellite = None
    if args.satellite.lower() != 'none':
        if args.satellite.lower() == 'auto':
            # resolve next to the static features so it works on any mirror
            sat_dir = Path(args.static_dir).resolve().parent / 'satellite'
            cands = (sorted(sat_dir.glob('*_grid.tif'))
                     or sorted(sat_dir.glob('*_512.tif'))
                     or sorted(sat_dir.glob('*.tif')))
            sat_path = cands[0] if cands else sat_dir / '(none found)'
        else:
            sat_path = Path(args.satellite)
        satellite = load_satellite(sat_path, grid)
        if satellite is None:
            print(f'[main] WARNING: satellite image {sat_path} not found — '
                  f'plotting without basemap')
        else:
            print(f'Basemap  : {sat_path}')

    stem = (f'asbury_{args.model_type}'
            f'_{times[0].strftime("%Y%m%d%H")}_{times[-1].strftime("%Y%m%d%H")}')
    if args.out_dir is not None:
        out_dir = Path(args.out_dir)
    else:
        exp_name = Path(args.ckpt_path).parent.parent.parent.name
        out_dir  = Path('predictions') / f'asbury_{exp_name}'

    print(f'Model    : {args.model_type}  |  checkpoint: {args.ckpt_path}')
    print(f'Rain     : {times[0]} → {times[-1]}  ({len(times)} hourly steps, local time)')
    print(f'Device   : {device}')
    print(f'Out dir  : {out_dir}')

    model = load_model(Path(args.ckpt_path), args.model_type, args).to(device)

    init_depth = init_rain = None
    if args.spinup_steps > 0:
        init_depth, init_rain = spin_up(
            model, static, args.spinup_steps, args.spinup_rain,
            args.patch_size, args.stride, device)
        # keep the generated initial condition inspectable
        ic_path = out_dir / f'{stem}_init_depth.tif'
        profile = grid['profile'].copy()
        profile.update(count=1, dtype='float32', nodata=None)
        ic_path.parent.mkdir(parents=True, exist_ok=True)
        with rasterio.open(ic_path, 'w', **profile) as dst:
            dst.write((init_depth * NORM_DEPTH / 1000.0).squeeze(0).numpy(), 1)
            dst.update_tags(1, description=(
                f'initial depth (m): {args.spinup_steps} h spin-up '
                f'at {args.spinup_rain} mm/hr uniform rain'))
        print(f'Saved initial condition → {ic_path}')

    zoom = None
    if args.zoom_shp:
        import geopandas as gpd
        zb = gpd.read_file(args.zoom_shp).to_crs(grid['crs']).total_bounds
        r0, c0 = rasterio.transform.rowcol(grid['transform'], zb[0], zb[3])
        r1, c1 = rasterio.transform.rowcol(grid['transform'], zb[2], zb[1])
        zoom = (max(0, r0), min(grid['height'], r1),
                max(0, c0), min(grid['width'], c1))
        print(f'Zoom     : {args.zoom_shp} -> rows {zoom[0]}:{zoom[1]}, cols {zoom[2]}:{zoom[3]}')

    preds = run_inference(
        model      = model,
        static     = static,
        rain_seq   = rain_seq,
        patch_size = args.patch_size,
        stride     = args.stride,
        device     = device,
        init_depth = init_depth,
        init_rain  = init_rain,
    )
    print(f'Predicted {len(preds)} steps')

    save_geotiff(preds, times, grid, out_dir / f'{stem}.tif')
    save_max_depth(preds, land_mask, grid, out_dir / stem, satellite=satellite,
                   zoom=zoom)
    if args.gif:
        save_gif(preds, times, rain_seq, land_mask, out_dir / f'{stem}.gif',
                 fps=args.fps, max_depth=args.max_depth, max_rain=args.max_rain,
                 satellite=satellite, zoom=zoom)


if __name__ == '__main__':
    main()
